def survey(root: str, scope: str = "", limit: int = 200) -> Dict[str, Any]:
    """Surveys the direct children of scope inside root without recursive walking.

    Args:
        root: Drive root path.
        scope: Subdirectory relative to root (default: "" for root).
        limit: Max entries to return in entries array (default: 200).

    Returns:
        Structured dictionary summarizing direct children, categories, units, and mess score.
    """
    root_abs = os.path.abspath(root)
    try:
        clean_scope = normalize_scope(scope, root_abs)
    except ValueError:
        clean_scope = scope.replace("\\", "/").strip("/")
    target_dir = os.path.join(root_abs, clean_scope) if clean_scope else root_abs
    is_root_scope = (clean_scope == "")
    mode = resolve_mode("auto", clean_scope)
    lock_reason = scope_lock_reason(root_abs, clean_scope)

    if not os.path.isdir(target_dir):
        return {
            "root": root_abs,
            "scope": clean_scope,
            "mode": mode,
            "locked": None,
            "index_available": False,
            "entries": [],
            "totals": {"files": 0, "dirs": 0, "loose_files": 0, "units_by_type": {}},
            "categories": {},
            "junk_count": 0,
            "mess_score": 0,
            "suggestions": ["Target directory does not exist."],
            "truncated": False,
        }

    db_path = get_default_db_path(root_abs)
    index_available = os.path.exists(db_path)

    entries_raw: List[Dict[str, Any]] = []
    file_count = 0
    dir_count = 0
    loose_files = 0
    junk_count = 0
    movable_count = 0
    units_by_type: Dict[str, int] = collections.defaultdict(int)
    categories: Dict[str, int] = collections.defaultdict(int)

    try:
        with os.scandir(target_dir) as it:
            scan_items = sorted(list(it), key=lambda e: e.name.lower())
    except (OSError, PermissionError):
        scan_items = []

    for entry in scan_items:
        try:
            st = entry.stat(follow_symlinks=False)
            mtime = st.st_mtime
            file_size = st.st_size
        except (OSError, PermissionError):
            mtime = 0.0
            file_size = 0

        if entry.is_file(follow_symlinks=False):
            file_count += 1
            size_bytes = file_size
            suggested_dst = None
            unit = None
            if is_tier1_junk(entry.name):
                junk_count += 1
            else:
                loose_files += 1
                if lock_reason is None:
                    suggested_dst, reason, conf = classify_file_target(
                        entry.name, mtime, mode=mode, scope=clean_scope, is_root_scope=is_root_scope
                    )

            src_rel = f"{clean_scope}/{entry.name}" if clean_scope else entry.name
            if suggested_dst is not None and suggested_dst != src_rel:
                movable_count += 1
                dest_dir = os.path.dirname(suggested_dst)
                categories[dest_dir] += 1

            entries_raw.append({
                "name": entry.name,
                "kind": "file",
                "unit": unit,
                "suggested_destination": suggested_dst,
                "size_bytes": size_bytes,
                "mtime": mtime,
            })

        elif entry.is_dir(follow_symlinks=False):
            dir_count += 1
            dir_rel = f"{clean_scope}/{entry.name}" if clean_scope else entry.name

            unit_type, suggested_dst, reason, conf = inspect_directory_unit(
                entry.path, entry.name, mode=mode, scope=clean_scope, is_root_scope=is_root_scope
            )
            if unit_type and unit_type != "mixed":
                units_by_type[unit_type] += 1
            if lock_reason is not None:
                suggested_dst = None

            if suggested_dst is not None and suggested_dst != dir_rel:
                movable_count += 1
                dest_dir = os.path.dirname(suggested_dst)
                categories[dest_dir] += 1

            entries_raw.append({
                "name": entry.name,
                "kind": "directory",
                "unit": unit_type if unit_type != "mixed" else None,
                "suggested_destination": suggested_dst,
                "size_bytes": None,
                "mtime": mtime,
                "_rel": dir_rel,
            })

    # Directory sizes come from the search index (one connection, closed afterwards). A range
    # query on the path keeps it index-friendly; LIKE would scan the whole table per folder and
    # treat "_" in names such as "01_AI_Models" as a wildcard.
    if index_available:
        db_mgr = None
        try:
            db_mgr = DatabaseManager(db_path)
            cur = db_mgr.get_connection().cursor()
            for e in entries_raw:
                if e["kind"] != "directory":
                    continue
                cur.execute(
                    "SELECT SUM(size) FROM files WHERE path >= ? AND path < ?;",
                    (e["_rel"] + "/", e["_rel"] + "0"),  # "0" is the character after "/"
                )
                row = cur.fetchone()
                if row and row[0] is not None:
                    e["size_bytes"] = int(row[0])
        except Exception:
            index_available = False
        finally:
            if db_mgr is not None:
                db_mgr.close()
    for e in entries_raw:
        e.pop("_rel", None)

    total_children = file_count + dir_count
    mess_score = int(round((movable_count / total_children) * 100)) if total_children > 0 else 0

    suggestions: List[str] = []
    if lock_reason is not None:
        suggestions.append(lock_reason)
    if movable_count > 0:
        suggestions.append(f"Run ssd_plan_organize to organize {movable_count} movable items.")
    if junk_count > 0:
        suggestions.append(f"Call ssd_clean to purge {junk_count} Tier-1 junk files.")
    if units_by_type:
        unit_summary = ", ".join(f"{count} {utype}" for utype, count in units_by_type.items())
        suggestions.append(f"Detected units ready for structured relocation: {unit_summary}.")
    if not suggestions:
        suggestions.append("Directory is clean and well organized.")

    truncated = len(entries_raw) > limit

    return {
        "root": root_abs,
        "scope": clean_scope,
        "mode": mode,
        "locked": lock_reason,
        "index_available": index_available,
        "entries": entries_raw[:limit],
        "totals": {
            "files": file_count,
            "dirs": dir_count,
            "loose_files": loose_files,
            "units_by_type": dict(units_by_type),
        },
        "categories": dict(categories),
        "junk_count": junk_count,
        "mess_score": mess_score,
        "suggestions": suggestions,
        "truncated": truncated,
    }


def propose_plan(
    root: str,
    scope: str = "",
    mode: str = "auto",
    detect_duplicates: bool = False,
    min_confidence: str = "low",
) -> Plan:
    """Proposes a deterministic organization plan for the direct children of scope.

    Args:
        root: Drive root path.
        scope: Subdirectory relative to root (default: "" for root).
        mode: Layout mode ('auto', 'zones' or 'in_place'); 'auto' tidies in place inside a
            zone folder and sorts into zones everywhere else.
        detect_duplicates: If True, detects identical duplicate files and proposes duplicates to _Duplicates_Review.
        min_confidence: Minimum confidence threshold ('low', 'medium', 'high').

    Returns:
        Plan object containing moves and kept items.
    """
    root_abs = os.path.abspath(root)
    try:
        clean_scope = normalize_scope(scope, root_abs)
    except ValueError:
        clean_scope = scope.replace("\\", "/").strip("/")
    target_dir = os.path.join(root_abs, clean_scope) if clean_scope else root_abs
    is_root_scope = (clean_scope == "")
    min_rank = CONFIDENCE_RANKS.get(min_confidence.lower(), 1)
    mode = resolve_mode(mode, clean_scope)

    moves: List[Move] = []
    kept: List[Dict[str, str]] = []
    created_at = datetime.datetime.now().isoformat()
    plan_id = f"plan-{secrets.token_hex(4)}"

    if not os.path.isdir(target_dir):
        return Plan(
            plan_id=plan_id,
            scope=clean_scope,
            mode=mode,
            created_at=created_at,
            moves=[],
            kept=[{"path": clean_scope, "reason": "Target directory does not exist"}],
        )

    lock_reason = scope_lock_reason(root_abs, clean_scope)
    if lock_reason:
        return Plan(
            plan_id=plan_id,
            scope=clean_scope,
            mode=mode,
            created_at=created_at,
            moves=[],
            kept=[{"path": clean_scope, "reason": lock_reason}],
        )

    try:
        with os.scandir(target_dir) as it:
            scan_items = sorted(list(it), key=lambda e: e.name.lower())
    except (OSError, PermissionError):
        scan_items = []

    # Handle duplicates among direct child files if requested
    dup_files_map: Dict[str, str] = {}  # file_path -> oldest_copy_path
    if detect_duplicates:
        child_files = [e for e in scan_items if e.is_file(follow_symlinks=False) and not is_tier1_junk(e.name)]
        size_groups: Dict[int, List[os.DirEntry]] = collections.defaultdict(list)
        for cf in child_files:
            try:
                sz = cf.stat().st_size
                size_groups[sz].append(cf)
            except OSError:
                pass

        for sz, flist in size_groups.items():
            if len(flist) < 2:
                continue
            # Hash files in size collisions
            hash_groups: Dict[str, List[os.DirEntry]] = collections.defaultdict(list)
            for cf in flist:
                try:
                    # Stream in 1 MB chunks: model files can be many GB.
                    digest = hashlib.sha256()
                    with open(cf.path, "rb") as f:
                        for chunk in iter(lambda: f.read(1024 * 1024), b""):
                            digest.update(chunk)
                    hash_groups[digest.hexdigest()].append(cf)
                except OSError:
                    pass

            for h, matches in hash_groups.items():
                if len(matches) < 2:
                    continue
                # Sort by mtime ascending (oldest first; tie-break by name)
                matches_sorted = sorted(
                    matches,
                    key=lambda e: (e.stat().st_mtime if hasattr(e.stat(), "st_mtime") else 0, e.name.lower())
                )
                oldest = matches_sorted[0]
                for dup in matches_sorted[1:]:
                    dup_files_map[dup.path] = oldest.name

    for entry in scan_items:
        src_rel = f"{clean_scope}/{entry.name}" if clean_scope else entry.name

        if entry.is_file(follow_symlinks=False):
            try:
                st = entry.stat(follow_symlinks=False)
                mtime = st.st_mtime
            except OSError:
                mtime = 0.0

            # 1. Duplicate check
            if entry.path in dup_files_map:
                oldest_name = dup_files_map[entry.path]
                dup_zone = f"06_Archives_Storage/_Duplicates_Review/{entry.name}"
                dest = format_destination(dup_zone, mode, clean_scope)
                reason = f"duplicate copy of {oldest_name}"
                conf = "medium"

                if CONFIDENCE_RANKS.get(conf, 1) < min_rank:
                    kept.append({"path": src_rel, "reason": f"confidence below threshold: {conf}"})
                elif dest == src_rel:
                    kept.append({"path": src_rel, "reason": "already at destination"})
                else:
                    moves.append(Move(src=src_rel, dst=dest, kind="file", reason=reason, confidence=conf))
                continue

            suggested_dst, reason, conf = classify_file_target(
                entry.name, mtime, mode=mode, scope=clean_scope, is_root_scope=is_root_scope
            )

            if suggested_dst is None:
                kept.append({"path": src_rel, "reason": reason or "kept"})
            elif suggested_dst == src_rel:
                kept.append({"path": src_rel, "reason": "already at destination"})
            elif conf and CONFIDENCE_RANKS.get(conf, 1) < min_rank:
                kept.append({"path": src_rel, "reason": f"confidence below threshold: {conf}"})
            else:
                moves.append(Move(src=src_rel, dst=suggested_dst, kind="file", reason=reason or "classified", confidence=conf or "high"))

        elif entry.is_dir(follow_symlinks=False):
            unit_type, suggested_dst, reason, conf = inspect_directory_unit(
                entry.path, entry.name, mode=mode, scope=clean_scope, is_root_scope=is_root_scope
            )

            if suggested_dst is None:
                kept.append({"path": src_rel, "reason": reason or "mixed folder"})
            elif suggested_dst == src_rel:
                kept.append({"path": src_rel, "reason": "already at destination"})
            elif conf and CONFIDENCE_RANKS.get(conf, 1) < min_rank:
                kept.append({"path": src_rel, "reason": f"confidence below threshold: {conf}"})
            else:
                moves.append(Move(src=src_rel, dst=suggested_dst, kind="directory", reason=reason or "unit", confidence=conf or "medium"))

    return Plan(
        plan_id=plan_id,
        scope=clean_scope,
        mode=mode,
        created_at=created_at,
        moves=moves,
        kept=kept,
    )


def validate_moves(root: str, moves: List[Union[Move, Dict[str, Any]]]) -> Dict[str, Any]:
    """Validates proposed moves against all exFAT/SSD and SmartDrive-OS invariants.

    Args:
        root: Drive root path.
        moves: List of Move objects or dictionaries with src, dst, kind.

    Returns:
        Validation report dictionary with per-move ok/error statuses.
    """
    root_abs = os.path.abspath(root)
    validated_moves: List[Dict[str, Any]] = []
    seen_srcs: Set[str] = set()
    seen_dsts: Set[str] = set()
    ok_count = 0
    error_count = 0

    for item in moves:
        if isinstance(item, Move):
            m_dict = item.to_dict()
        elif isinstance(item, dict):
            m_dict = dict(item)
        else:
            m_dict = {"src": str(item), "dst": "", "kind": "file", "reason": "unknown", "confidence": "low"}

        src_raw = m_dict.get("src", "")
        dst_raw = m_dict.get("dst", "")
        kind = m_dict.get("kind", "file")

        error_msg: Optional[str] = None

        # Normalize relative paths
        src_rel = src_raw.replace("\\", "/").strip("/")
        dst_rel = dst_raw.replace("\\", "/").strip("/")

        # 1. Duplicate source or destination in plan. Compared case-insensitively: exFAT, NTFS and
        # APFS fold case, so "Images/A.jpg" and "images/a.jpg" are the same destination.
        src_key = src_rel.casefold()
        dst_key = dst_rel.casefold()
        if src_key in seen_srcs:
            error_msg = f"Duplicate source path in plan: '{src_rel}'"
        elif dst_key in seen_dsts:
            error_msg = f"Duplicate destination path in plan: '{dst_rel}'"
        else:
            seen_srcs.add(src_key)
            seen_dsts.add(dst_key)

        # 2. Basic non-empty path check
        if error_msg is None:
            if not src_rel:
                error_msg = "Cannot move drive root"
            elif not dst_rel:
                error_msg = "Destination path cannot be empty"

        # 3. Containment / Root escape check
        if error_msg is None:
            try:
                normalize_rel_path(os.path.join(root_abs, src_rel), root_abs, strict=True)
                normalize_rel_path(os.path.join(root_abs, dst_rel), root_abs, strict=True)
            except (ValueError, Exception) as exc:
                error_msg = f"Path escapes drive root boundary: {exc}"

        src_abs = os.path.join(root_abs, src_rel)
        dst_abs = os.path.join(root_abs, dst_rel)

        # 4. Source existence & kind check (an unknown kind is taken from the disk)
        if error_msg is None:
            if not os.path.exists(src_abs):
                error_msg = f"Source does not exist: '{src_rel}'"
            elif kind not in ("file", "directory"):
                kind = "directory" if os.path.isdir(src_abs) else "file"
                m_dict["kind"] = kind
            elif kind == "file" and not os.path.isfile(src_abs):
                error_msg = f"Source is not a file: '{src_rel}'"
            elif kind == "directory" and not os.path.isdir(src_abs):
                error_msg = f"Source is not a directory: '{src_rel}'"

        # 5. Symlink guard
        if error_msg is None:
            if is_symlink(src_abs):
                error_msg = f"Cannot move symlink or junction: '{src_rel}'"

        # 6. Protected entities guard
        if error_msg is None:
            src_base = os.path.basename(src_rel)
            if src_rel in TAXONOMY_ROOT_DIRS or src_rel in PROTECTED_CORE_TAXONOMIES:
                error_msg = f"Cannot move taxonomy root directory: '{src_rel}'"
            elif is_protected_root_dir(src_rel) or is_protected_root_file(src_rel):
                error_msg = f"Cannot move protected root entity: '{src_rel}'"
            elif src_base.startswith("."):
                error_msg = f"Cannot move hidden entity: '{src_rel}'"

        # 7. Source inside project/app unit or .git repository
        if error_msg is None:
            if is_inside_unit_or_repo(root_abs, src_rel):
                error_msg = f"Source is located inside a project unit, app unit, or repository: '{src_rel}'"

        # 8. Destination inside source itself
        if error_msg is None:
            if dst_rel == src_rel or dst_rel.startswith(src_rel + "/"):
                error_msg = f"Destination '{dst_rel}' is inside source directory '{src_rel}'"

        # 9. Destination inside hidden or unit directory
        if error_msg is None:
            dst_parts = dst_rel.split("/")
            for p in dst_parts[:-1]:
                if p.startswith("."):
                    error_msg = f"Destination '{dst_rel}' is inside hidden or system directory '{p}'"
                    break
            if error_msg is None and is_inside_unit_or_repo(root_abs, dst_rel):
                error_msg = f"Destination '{dst_rel}' is inside a project unit, app unit, or repository"

        # 10. Destination collision guard (never overwrite, never rename)
        if error_msg is None:
            if os.path.exists(dst_abs):
                error_msg = f"Destination already exists (cannot overwrite or rename): '{dst_rel}'"

        # 11. Windows / exFAT naming compatibility check on destination
        if error_msg is None:
            for component in dst_rel.split("/"):
                violations = audit_forbidden_characters(component)
                if violations:
                    error_msg = f"Destination component '{component}' contains invalid characters or reserved names: {violations}"
                    break

        if error_msg is None:
            status = "ok"
            ok_count += 1
        else:
            status = "error"
            error_count += 1

        m_dict["src"] = src_rel
        m_dict["dst"] = dst_rel
        m_dict["status"] = status
        m_dict["error"] = error_msg
        validated_moves.append(m_dict)

    all_valid = (error_count == 0 and len(validated_moves) > 0) or (len(validated_moves) == 0)

    return {
        "valid": all_valid,
        "summary": {
            "total": len(validated_moves),
            "ok": ok_count,
            "errors": error_count,
        },
        "moves": validated_moves,
    }


def _generate_index_markdown(dir_path: str, dir_name: str, recent_moves: List[Dict[str, Any]]) -> str:
    """Generates the content for _INDEX.md with folder counts and recent moves."""
    lines = [
        INDEX_MARKER,
        f"# {dir_name} Index",
        "",
        "## Sub-folders",
        "",
        "| Folder | Direct Files |",
        "| :--- | :--- |",
    ]

    subfolder_rows = []
    try:
        with os.scandir(dir_path) as it:
            for entry in sorted(list(it), key=lambda e: e.name.lower()):
                if entry.is_dir(follow_symlinks=False) and not entry.name.startswith("."):
                    fcount = 0
                    try:
                        with os.scandir(entry.path) as sub_it:
                            fcount = sum(1 for se in sub_it if se.is_file(follow_symlinks=False))
                    except (OSError, PermissionError):
                        pass
                    subfolder_rows.append(f"| `{entry.name}` | {fcount:,} |")
    except (OSError, PermissionError):
        pass

    if subfolder_rows:
        lines.extend(subfolder_rows)
    else:
        lines.append("| *(none)* | 0 |")

    if recent_moves:
        lines.extend([
            "",
            "## Recently Organized",
            "",
            "| Original Source | Destination | Kind |",
            "| :--- | :--- | :--- |",
        ])
        for rm in recent_moves[:50]:
            lines.append(f"| `{rm.get('src', '')}` | `{rm.get('dst', '')}` | {rm.get('kind', 'file')} |")

    lines.append("")
    return "\n".join(lines)


def _safe_write_index_md(dir_path: str, dir_name: str, recent_moves: List[Dict[str, Any]]) -> bool:
    """Writes _INDEX.md only if it does not exist or was generated by SmartDrive."""
    index_file = os.path.join(dir_path, "_INDEX.md")
    if os.path.exists(index_file):
        try:
            with open(index_file, "r", encoding="utf-8", errors="replace") as f:
                first_line = f.readline().strip()
            if first_line != INDEX_MARKER:
                # User-authored _INDEX.md: preserve untouched
                return False
        except (OSError, PermissionError):
            return False

    content = _generate_index_markdown(dir_path, dir_name, recent_moves)
    try:
        with open(index_file, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        return True
    except (OSError, PermissionError):
        return False


JOURNAL_ID_PATTERN = re.compile(r"^\d{8}-\d{6}-[0-9a-f]{6}$")


def _append_journal_event(jf: Any, event: Dict[str, Any]) -> None:
    """Appends one event line to an open journal and forces it to disk."""
    jf.write(json.dumps(event) + "\n")
    jf.flush()
    try:
        os.fsync(jf.fileno())
    except OSError:
        pass


def _rename_no_clobber(src_abs: str, dst_abs: str) -> None:
    """Renames src to dst without ever replacing what is already at dst.

    os.rename silently replaces an existing file (and an empty directory) on macOS and Linux,
    so the destination is re-checked immediately before renaming. Windows refuses on its own.
    """
    if os.path.lexists(dst_abs):
        raise FileExistsError(f"Destination appeared after validation: '{dst_abs}'")
    os.rename(src_abs, dst_abs)


def _sync_index_for_moves(root_abs: str, moves: List[Dict[str, Any]]) -> Optional[str]:
    """Re-indexes only what the moves touched; returns an error message, or None on success.

    Each vacated source path is synced (its rows are dropped because it no longer exists) and
    each destination is synced: the moved directory itself, or the parent folder of a moved
    file. The drive root is never used as a scope, since that would rescan the whole drive.
    """
    db_path = get_default_db_path(root_abs)
    if not os.path.exists(db_path):
        return None
    scopes: List[str] = []
    for m in moves:
        dst = m["dst"]
        dst_scope = dst if m.get("kind") == "directory" else (posixpath.dirname(dst) or dst)
        for scope in (m["src"], dst_scope):
            if scope and scope not in scopes:
                scopes.append(scope)
    try:
        db_mgr = DatabaseManager(db_path)
        try:
            idx_mgr = IndexManager(db_mgr, root_abs)
            for scope in scopes:
                idx_mgr.incremental_update(directory=scope)
        finally:
            db_mgr.close()
    except Exception as exc:
        return f"Search index update failed: {exc}. Run ssd_update_index to resync."
    return None


def apply_moves(
    root: str,
    moves: List[Union[Move, Dict[str, Any]]],
    apply: bool = False,
    write_index: bool = True,
    mode: str = "zones",
    scope: str = "",
) -> Dict[str, Any]:
    """Validates and executes organization moves with full atomic JSONL journaling.

    Args:
        root: Drive root path.
        moves: List of Move objects or dictionaries.
        apply: If True, executes moves on disk. If False, runs simulation preview.
        write_index: If True, generates/updates _INDEX.md in touched folders.
        mode: Organization mode ('zones' or 'in_place').
        scope: Scope directory.

    Returns:
        Execution report dictionary.
    """
    root_abs = os.path.abspath(root)
    mode = resolve_mode(mode, scope.replace("\\", "/").strip("/") if scope else "")
    val_report = validate_moves(root_abs, moves)
    ok_moves = [m for m in val_report["moves"] if m.get("status") == "ok"]

    if not apply:
        return {
            "status": "dry_run",
            "valid": val_report["valid"],
            "total_moves": len(val_report["moves"]),
            "ok_moves": len(ok_moves),
            "error_moves": val_report["summary"]["errors"],
            "moves": val_report["moves"],
        }

    journal_dir = os.path.join(root_abs, ".smart_drive", "journal")
    os.makedirs(journal_dir, exist_ok=True)
    timestamp_str = time.strftime("%Y%m%d-%H%M%S")
    rand_hex = secrets.token_hex(3)
    journal_id = f"{timestamp_str}-{rand_hex}"
    journal_path = os.path.join(journal_dir, f"{journal_id}.jsonl")

    done_moves: List[Dict[str, Any]] = []
    failed_moves: List[Dict[str, Any]] = []
    touched_top_dirs: Set[str] = set()

    with open(journal_path, "w", encoding="utf-8", newline="\n") as jf:
        # Write header first, flushed and fsynced BEFORE any rename
        header_event = {
            "event": "start",
            "journal_id": journal_id,
            "timestamp": datetime.datetime.now().isoformat(),
            "total": len(ok_moves),
            "mode": mode,
            "scope": scope,
        }
        jf.write(json.dumps(header_event) + "\n")
        jf.flush()
        try:
            os.fsync(jf.fileno())
        except OSError:
            pass

        for m in ok_moves:
            src_rel = m["src"]
            dst_rel = m["dst"]
            kind = m.get("kind", "file")
            src_abs = os.path.join(root_abs, src_rel)
            dst_abs = os.path.join(root_abs, dst_rel)
            dst_parent = os.path.dirname(dst_abs)

            # Discover directories created for this move
            newly_created: List[str] = []
            curr = dst_parent
            while curr and curr != root_abs and not os.path.exists(curr):
                newly_created.append(curr)
                curr = os.path.dirname(curr)

            created_rel = [normalize_rel_path(d, root_abs) for d in reversed(newly_created)]
            # Record the intent before touching the disk, so a crash between the rename and the
            # "done" line still leaves enough in the journal for undo to find the file.
            _append_journal_event(jf, {
                "event": "move",
                "status": "begin",
                "src": src_rel,
                "dst": dst_rel,
                "kind": kind,
                "created_dirs": created_rel,
            })

            try:
                if newly_created:
                    os.makedirs(dst_parent, exist_ok=True)
                _rename_no_clobber(src_abs, dst_abs)
            except Exception as exc:
                failed_record = {
                    "event": "move",
                    "status": "failed",
                    "src": src_rel,
                    "dst": dst_rel,
                    "kind": kind,
                    "error": str(exc),
                }
                _append_journal_event(jf, failed_record)
                failed_moves.append(failed_record)
                continue

            # Outside the try above: if writing "done" fails, the move must not be reported as
            # failed. The "begin" line already on disk lets undo recover it.
            done_record = {
                "event": "move",
                "status": "done",
                "src": src_rel,
                "dst": dst_rel,
                "kind": kind,
                "created_dirs": created_rel,
            }
            _append_journal_event(jf, done_record)
            done_moves.append(done_record)
            touched_top_dirs.add(src_rel.split("/")[0])
            touched_top_dirs.add(dst_rel.split("/")[0])

        # Write finish event
        finish_status = "completed" if len(failed_moves) == 0 else "partial"
        finish_event = {
            "event": "finish",
            "status": finish_status,
            "done_count": len(done_moves),
            "failed_count": len(failed_moves),
            "timestamp": datetime.datetime.now().isoformat(),
        }
        jf.write(json.dumps(finish_event) + "\n")
        jf.flush()
        try:
            os.fsync(jf.fileno())
        except OSError:
            pass

    index_error = _sync_index_for_moves(root_abs, done_moves)

    # Write _INDEX.md in touched zones or scope
    if write_index:
        if mode == "zones":
            for t_dir in touched_top_dirs:
                zone_path = os.path.join(root_abs, t_dir)
                if t_dir in TAXONOMY_ROOT_DIRS and os.path.isdir(zone_path):
                    zone_moves = [m for m in done_moves if m.get("dst", "").startswith(t_dir + "/")]
                    _safe_write_index_md(zone_path, t_dir, zone_moves)
        else:
            clean_scope = ""
            try:
                clean_scope = normalize_scope(scope, root_abs)
            except ValueError:
                clean_scope = scope.replace("\\", "/").strip("/")
            target_scope_dir = os.path.join(root_abs, clean_scope) if clean_scope else root_abs
            if os.path.isdir(target_scope_dir):
                scope_name = os.path.basename(target_scope_dir) or "Drive Root"
                _safe_write_index_md(target_scope_dir, scope_name, done_moves)

    return {
        "status": "applied",
        "journal_id": journal_id,
        "journal_path": journal_path,
        "total_moves": len(ok_moves),
        "moved": len(done_moves),
        "failed": len(failed_moves),
        "errors": [f.get("error") for f in failed_moves],
        "index_error": index_error,
        "moves": done_moves,
    }


def undo_journal(root: str, journal_id: str, apply: bool = False) -> Dict[str, Any]:
    """Rolls back the moves of a journaled organization run in reverse order.

    Args:
        root: Drive root path.
        journal_id: Journal identifier or filename.
        apply: If True, executes the rollback on disk. If False, previews undo.

    Returns:
        Undo execution report.
    """
    root_abs = os.path.abspath(root)
    clean_id = journal_id.strip()
    if clean_id.endswith(".jsonl"):
        clean_id = clean_id[:-6]

    journal_dir = os.path.join(root_abs, ".smart_drive", "journal")

    def _error(message: str) -> Dict[str, Any]:
        return {
            "status": "error",
            "journal_id": journal_id,
            "error": message,
            "undone_count": 0,
            "conflict_count": 0,
            "conflicts": [],
        }

    # Only ids this module generates are accepted: an exact id or an unambiguous prefix of one.
    # Anything else (empty, "..", path separators) could point the undo at a file outside the
    # journal folder, whose entries would then drive renames.
    if not clean_id or not re.fullmatch(r"[0-9a-f-]+", clean_id):
        return _error(f"Invalid journal id '{journal_id}'. Use an id from ssd_list_journals.")
    known_ids: List[str] = []
    if os.path.isdir(journal_dir):
        try:
            known_ids = sorted(
                fname[:-6] for fname in os.listdir(journal_dir)
                if fname.endswith(".jsonl") and JOURNAL_ID_PATTERN.match(fname[:-6])
            )
        except OSError:
            known_ids = []
    matches = [clean_id] if clean_id in known_ids else [jid for jid in known_ids if jid.startswith(clean_id)]
    if not matches:
        return _error(f"Journal file '{journal_id}' not found in '{journal_dir}'")
    if len(matches) > 1:
        return _error(f"Journal id '{journal_id}' is ambiguous; it matches {', '.join(matches[:5])}")
    clean_id = matches[0]
    journal_path = os.path.join(journal_dir, f"{clean_id}.jsonl")

    done_moves: List[Dict[str, Any]] = []
    created_dirs_set: List[str] = []
    pending: Dict[Tuple[str, str], Dict[str, Any]] = {}
    already_undone = False

    with open(journal_path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line_str = line.strip()
            if not line_str:
                continue
            try:
                event = json.loads(line_str)
            except Exception:
                continue
            if event.get("event") == "undo" and event.get("status") == "completed":
                already_undone = True
            if event.get("event") != "move":
                continue
            key = (event.get("src", ""), event.get("dst", ""))
            status = event.get("status")
            if status == "begin":
                pending[key] = event
            elif status == "done":
                pending.pop(key, None)
                done_moves.append(event)
            elif status == "failed":
                pending.pop(key, None)
            if status in ("begin", "done"):
                for cd in event.get("created_dirs", []):
                    if cd not in created_dirs_set:
                        created_dirs_set.append(cd)

    if already_undone:
        return _error(f"Journal '{clean_id}' has already been undone.")

    # A "begin" with no outcome means the run stopped mid-move. If the item did reach its
    # destination, treat that move as done so it is undone too.
    for (pend_src, pend_dst), event in pending.items():
        if (
            pend_src and pend_dst
            and os.path.lexists(os.path.join(root_abs, pend_dst))
            and not os.path.lexists(os.path.join(root_abs, pend_src))
        ):
            done_moves.append(event)

    # Reversal in reverse order (LIFO)
    reverse_moves = list(reversed(done_moves))
    conflicts: List[Dict[str, str]] = []
    planned_undone: List[Dict[str, str]] = []

    for mv in reverse_moves:
        orig_src = mv.get("src", "")  # Where it will be restored to
        orig_dst = mv.get("dst", "")  # Where it currently is
        curr_abs = os.path.join(root_abs, orig_dst)
        target_abs = os.path.join(root_abs, orig_src)

        # The journal lives on the drive and could have been edited: re-check every entry.
        try:
            normalize_rel_path(curr_abs, root_abs, strict=True)
            normalize_rel_path(target_abs, root_abs, strict=True)
            inside_root = bool(orig_src and orig_dst)
        except Exception:
            inside_root = False
        if not inside_root:
            conflicts.append({"path": orig_src, "reason": "Journal entry is empty or points outside the drive root; skipped"})
        elif is_protected_root_dir(orig_src) or is_protected_root_file(orig_src):
            conflicts.append({"path": orig_src, "reason": "Journal entry targets a protected path; skipped"})
        elif not os.path.exists(curr_abs):
            conflicts.append({"path": orig_dst, "reason": "Target file to restore is missing from current location"})
        elif os.path.exists(target_abs):
            conflicts.append({"path": orig_src, "reason": "Original restoration destination is already occupied"})
        else:
            planned_undone.append({"src": orig_dst, "dst": orig_src, "kind": mv.get("kind", "file")})

    if not apply:
        return {
            "status": "dry_run",
            "journal_id": clean_id,
            "total_done_moves": len(done_moves),
            "can_undo_count": len(planned_undone),
            "conflict_count": len(conflicts),
            "conflicts": conflicts,
            "planned_restores": planned_undone,
        }

    undone_count = 0
    restored: List[Dict[str, Any]] = []
    for mv in planned_undone:
        curr_abs = os.path.join(root_abs, mv["src"])
        target_abs = os.path.join(root_abs, mv["dst"])
        try:
            os.makedirs(os.path.dirname(target_abs), exist_ok=True)
            _rename_no_clobber(curr_abs, target_abs)
            undone_count += 1
            restored.append(mv)
        except Exception as exc:
            conflicts.append({"path": mv["src"], "reason": str(exc)})

    # Remove created directories if they are now empty
    for c_dir in reversed(created_dirs_set):
        c_abs = os.path.join(root_abs, c_dir)
        if os.path.isdir(c_abs):
            try:
                os.rmdir(c_abs)
            except OSError:
                pass

    # Append undo record to journal
    undo_status = "completed" if len(conflicts) == 0 else "partial"
    undo_record = {
        "event": "undo",
        "status": undo_status,
        "undone_count": undone_count,
        "conflict_count": len(conflicts),
        "timestamp": datetime.datetime.now().isoformat(),
    }
    with open(journal_path, "a", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(undo_record) + "\n")
        f.flush()
        try:
            os.fsync(f.fileno())
        except OSError:
            pass

    index_error = _sync_index_for_moves(root_abs, restored)

    return {
        "status": "applied",
        "journal_id": clean_id,
        "undone_count": undone_count,
        "conflict_count": len(conflicts),
        "conflicts": conflicts,
        "index_error": index_error,
    }


def list_journals(root: str) -> List[Dict[str, Any]]:
    """Lists all organization journals found on the drive root.

    Args:
        root: Drive root path.

    Returns:
        List of journal metadata dictionaries sorted descending by date.
    """
    root_abs = os.path.abspath(root)
    journal_dir = os.path.join(root_abs, ".smart_drive", "journal")
    if not os.path.isdir(journal_dir):
        return []

    journals: List[Dict[str, Any]] = []

    try:
        filenames = sorted(os.listdir(journal_dir), reverse=True)
    except OSError:
        filenames = []

    for fname in filenames:
        if not fname.endswith(".jsonl"):
            continue
        journal_id = fname[:-6]
        fpath = os.path.join(journal_dir, fname)

        created_at = ""
        scope = ""
        mode = "zones"
        total_moves = 0
        done_moves = 0
        failed_moves = 0
        final_status = "unknown"
        is_undone = False

        try:
            with open(fpath, "r", encoding="utf-8", errors="replace") as f:
                for line in f:
                    line_str = line.strip()
                    if not line_str:
                        continue
                    try:
                        event = json.loads(line_str)
                    except Exception:
                        continue

                    ev_type = event.get("event")
                    if ev_type == "start":
                        created_at = event.get("timestamp", "")
                        scope = event.get("scope", "")
                        mode = event.get("mode", "zones")
                        total_moves = event.get("total", 0)
                    elif ev_type == "move":
                        # "begin" lines only record intent; each move ends as "done" or "failed".
                        if event.get("status") == "done":
                            done_moves += 1
                        elif event.get("status") == "failed":
                            failed_moves += 1
                    elif ev_type == "finish":
                        final_status = event.get("status", "completed")
                    elif ev_type == "undo":
                        undo_status = event.get("status")
                        is_undone = is_undone or undo_status == "completed"
                        if undo_status == "partial" and not is_undone:
                            final_status = "partially undone"
        except OSError:
            continue

        display_status = "undone" if is_undone else final_status

        journals.append({
            "id": journal_id,
            "created_at": created_at,
            "scope": scope,
            "mode": mode,
            "status": display_status,
            "total_moves": total_moves,
            "done_moves": done_moves,
            "failed_moves": failed_moves,
        })

    return journals


