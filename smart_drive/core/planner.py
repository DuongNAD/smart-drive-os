def strip_accents(text: str) -> str:
    """Strips combining diacritics from text (e.g. 'Ảnh' -> 'Anh')."""
    nfkd = unicodedata.normalize("NFKD", text)
    return "".join(c for c in nfkd if not unicodedata.combining(c))


def is_screenshot_name(filename: str) -> bool:
    """Checks if filename starts with a screenshot prefix (case/accent insensitive)."""
    stem = os.path.splitext(filename)[0].strip().lower()
    stem_no_accents = strip_accents(stem)
    for prefix in SCREENSHOT_PREFIXES:
        if stem.startswith(prefix) or stem_no_accents.startswith(prefix):
            return True
    return False


def is_tier1_junk(name: str) -> bool:
    """Checks if a file is Tier-1 junk (.DS_Store, ._*, Thumbs.db, desktop.ini)."""
    name_lower = name.lower()
    if name_lower.startswith("._"):
        return True
    if name_lower in TIER1_JUNK_EXACT:
        return True
    return False


def get_default_db_path(root: str) -> str:
    """Default location for the SQLite search database."""
    new_path = os.path.join(root, ".smart_drive", "index.db")
    if os.path.exists(new_path):
        return new_path
    legacy_path = os.path.join(root, ".smart_drive_manager", "index.db")
    if os.path.exists(legacy_path):
        return legacy_path
    return new_path


def normalize_scope(scope: str, root_abs: str) -> str:
    """Normalizes and bounds a scope path relative to drive root.

    Handles empty strings, relative paths ('Downloads/test'), and absolute paths
    ('D:/Downloads' or '/Volumes/DRIVE/Downloads') safely without relying on CWD.
    """
    if not scope:
        return ""
    scope_str = str(scope).strip()
    if not scope_str or scope_str == ".":
        return ""
    # If absolute or starts with drive letter
    if os.path.isabs(scope_str) or (len(scope_str) >= 2 and scope_str[1] == ":"):
        return normalize_rel_path(scope_str, root_abs, strict=True)
    # Relative path: sanitize slashes and check for ../ escaping
    clean = scope_str.replace("\\", "/").strip("/")
    parts = [p for p in clean.split("/") if p and p != "."]
    resolved = []
    for p in parts:
        if p == "..":
            if resolved:
                resolved.pop()
            else:
                raise ValueError(f"Scope '{scope}' escapes drive root boundary")
        else:
            resolved.append(p)
    return "/".join(resolved)


ZONE_NAMES_FOLDED: Set[str] = {z.casefold() for z in tuple(TAXONOMY_ROOT_DIRS) + tuple(PROTECTED_CORE_TAXONOMIES)}

# Files that describe the folder they sit in; moving them away orphans the folder's docs/rules.
FOLDER_MANIFEST_PATTERNS: Tuple[str, ...] = (
    "readme*", "license*", "licence*", "changelog*", "contributing*",
    "agents.md", "gemini.md", "claude.md", "index.md", "_index.md",
)


def is_folder_manifest(filename: str) -> bool:
    """Checks if a file documents its own folder (README, LICENSE, AGENTS.md, INDEX.md...)."""
    name = filename.lower()
    return any(fnmatch.fnmatch(name, pattern) for pattern in FOLDER_MANIFEST_PATTERNS)


def resolve_mode(mode: Optional[str], scope: str) -> str:
    """Turns "auto" into a concrete layout: tidy in place inside a zone folder, sort into zones elsewhere.

    Sorting a zone's contents into other zones would scatter it (a study project kept in
    02_Learning_Knowledge is not a 03_Development_Projects item), so "auto" keeps them home.
    """
    clean = (mode or "auto").lower()
    if clean != "auto":
        return clean
    first = scope.replace("\\", "/").strip("/").split("/")[0] if scope else ""
    return "in_place" if first and first.casefold() in ZONE_NAMES_FOLDED else "zones"


def scope_lock_reason(root_abs: str, scope: str) -> Optional[str]:
    """Explains why a scope must not be reorganized (it sits in a repo/project), or returns None."""
    if scope and is_inside_unit_or_repo(root_abs, f"{scope}/_"):
        return (
            f"'{scope}' is inside a git repository or project folder; reorganizing it would rewrite "
            "that project. Move the project as a whole from its parent folder instead."
        )
    return None


def _to_in_place_subpath(zone_subpath: str) -> str:
    """Transforms a standard zone subpath into its in_place relative subpath."""
    parts = zone_subpath.split("/")
    if not parts:
        return zone_subpath
    prefix = parts[0]
    remainder = parts[1:]

    if prefix == "03_Development_Projects":
        return "/".join(["Projects"] + remainder)
    if prefix == "05_Dev_Toolbox" and len(remainder) >= 1 and remainder[0] == "Portable_Apps":
        return "/".join(["Apps"] + remainder[1:])
    if len(parts) > 1:
        return "/".join(remainder)
    return zone_subpath


def format_destination(zone_subpath: str, mode: str, scope: str) -> str:
    """Formats the target destination relative path based on mode and scope."""
    if mode == "in_place":
        in_place_sub = _to_in_place_subpath(zone_subpath)
        if scope:
            clean_scope = scope.replace("\\", "/").strip("/")
            return f"{clean_scope}/{in_place_sub}"
        return in_place_sub
    return zone_subpath


def classify_file_target(
    filename: str,
    mtime: float,
    mode: str = "zones",
    scope: str = "",
    is_root_scope: bool = False,
) -> Tuple[Optional[str], Optional[str], Optional[str]]:
    """Classifies a file entry and returns (suggested_dst_rel, reason, confidence).

    If the file should be kept (not moved), returns (None, keep_reason, None).
    """
    # 1. Tier-1 junk check
    if is_tier1_junk(filename):
        return None, "tier-1 junk - use ssd_clean to purge", None

    # 2. Hidden files
    if filename.startswith("."):
        return None, "hidden file", None

    # 2b. Files that document their folder stay with it
    if is_folder_manifest(filename):
        return None, "folder manifest kept with its folder", None

    # 3. Root scope protections
    if is_root_scope:
        if is_protected_root_file(filename):
            return None, "protected root file", None
        if filename.lower().endswith(".md"):
            return None, "root markdown document kept", None
        ext = os.path.splitext(filename)[1].lower()
        if ext in ROOT_LAUNCHER_EXTS:
            return None, "root launcher kept", None

    ext = os.path.splitext(filename)[1].lower()
    mtime_struct = time.localtime(mtime)

    # 4. Check AI Models
    if ext in EXT_AI_GGUF:
        dest = format_destination(f"01_AI_Models/GGUF/{filename}", mode, scope)
        return dest, "GGUF AI model", "high"
    if ext in EXT_AI_SAFETENSORS:
        dest = format_destination(f"01_AI_Models/SafeTensors/{filename}", mode, scope)
        return dest, "SafeTensors model", "high"
    if ext in EXT_AI_CHECKPOINTS:
        dest = format_destination(f"01_AI_Models/Checkpoints/{filename}", mode, scope)
        return dest, "AI model checkpoint", "high"
    if ext in EXT_AI_DATASETS:
        dest = format_destination(f"01_AI_Models/Datasets/{filename}", mode, scope)
        return dest, "AI dataset", "high"

    # 5. Check Learning & Knowledge
    if ext in EXT_BOOKS:
        dest = format_destination(f"02_Learning_Knowledge/Books/{filename}", mode, scope)
        return dest, "e-book", "high"
    if ext == ".pdf" and ARXIV_REGEX.search(filename):
        dest = format_destination(f"02_Learning_Knowledge/Papers/{filename}", mode, scope)
        return dest, "arXiv paper", "medium"
    if ext in EXT_DOCS_SLIDES:
        match = COURSE_CODE_REGEX.search(filename)
        if match:
            code = match.group(1)
            dest = format_destination(f"02_Learning_Knowledge/Courses/{code}/{filename}", mode, scope)
            return dest, f"Course {code} document", "medium"

    # 6. Check Personal Documents
    if ext == ".pdf":
        dest = format_destination(f"03_Personal_Documents/PDF/{filename}", mode, scope)
        return dest, "PDF document", "high"
    if ext in EXT_OFFICE:
        dest = format_destination(f"03_Personal_Documents/Office/{filename}", mode, scope)
        return dest, "Office document", "high"

    # 7. Check Creative Assets
    if is_screenshot_name(filename):
        date_ym = time.strftime("%Y-%m", mtime_struct)
        dest = format_destination(f"04_Creative_Assets/Screenshots/{date_ym}/{filename}", mode, scope)
        return dest, "screenshot", "medium"
    if ext in EXT_IMAGES:
        date_y = time.strftime("%Y", mtime_struct)
        date_ym = time.strftime("%Y-%m", mtime_struct)
        dest = format_destination(f"04_Creative_Assets/Images/{date_y}/{date_ym}/{filename}", mode, scope)
        return dest, "image", "high"
    if ext in EXT_VIDEOS:
        date_y = time.strftime("%Y", mtime_struct)
        dest = format_destination(f"04_Creative_Assets/Videos/{date_y}/{filename}", mode, scope)
        return dest, "video", "high"
    if ext in EXT_AUDIO:
        dest = format_destination(f"04_Creative_Assets/Audio/{filename}", mode, scope)
        return dest, "audio", "high"
    if ext in EXT_DESIGN:
        dest = format_destination(f"04_Creative_Assets/Design/{filename}", mode, scope)
        return dest, "design asset", "high"
    if ext in EXT_3D:
        dest = format_destination(f"04_Creative_Assets/3D_Models/{filename}", mode, scope)
        return dest, "3D model", "high"
    if ext in EXT_FONTS:
        dest = format_destination(f"04_Creative_Assets/Fonts/{filename}", mode, scope)
        return dest, "font", "high"

    # 8. Check Dev Toolbox
    if ext in EXT_INSTALLERS_WIN:
        dest = format_destination(f"05_Dev_Toolbox/Installers/Windows/{filename}", mode, scope)
        return dest, "Windows installer", "high"
    if ext in EXT_INSTALLERS_MAC:
        dest = format_destination(f"05_Dev_Toolbox/Installers/macOS/{filename}", mode, scope)
        return dest, "macOS installer", "high"
    if ext in EXT_INSTALLERS_LINUX:
        dest = format_destination(f"05_Dev_Toolbox/Installers/Linux/{filename}", mode, scope)
        return dest, "Linux installer", "high"
    if ext in EXT_SCRIPTS:
        dest = format_destination(f"05_Dev_Toolbox/Scripts/{filename}", mode, scope)
        return dest, "script", "high"

    # 9. Check Archives & Storage
    if ext in EXT_ARCHIVES:
        dest = format_destination(f"06_Archives_Storage/Archives/{filename}", mode, scope)
        return dest, "archive", "high"
    if ext in EXT_DISK_IMAGES:
        dest = format_destination(f"06_Archives_Storage/Disk_Images/{filename}", mode, scope)
        return dest, "disk image", "high"
    if ext in EXT_BACKUPS:
        dest = format_destination(f"06_Archives_Storage/Backups/{filename}", mode, scope)
        return dest, "backup file", "high"

    # 10. Unrecognised extension fallback
    dest = format_destination(f"06_Archives_Storage/_Unsorted/{filename}", mode, scope)
    return dest, "unrecognized extension", "low"


def inspect_directory_unit(
    dir_path: str,
    dir_name: str,
    mode: str = "zones",
    scope: str = "",
    is_root_scope: bool = False,
) -> Tuple[Optional[str], Optional[str], Optional[str], Optional[str]]:
    """Inspects a directory and determines if it is a protected, project, app, course, album, or mixed unit.

    Returns:
        (unit_type, suggested_dst_rel, reason, confidence)
        If kept, suggested_dst_rel is None and reason explains why.
    """
    # 1. Hard protected & hidden check
    name_lower = dir_name.lower()
    if is_root_scope:
        if is_protected_root_dir(dir_name) or dir_name in TAXONOMY_ROOT_DIRS or dir_name in PROTECTED_CORE_TAXONOMIES:
            return None, None, "protected root directory", None

    if dir_name.startswith("."):
        return None, None, "hidden directory", None

    if name_lower in {"$recycle.bin", "system volume information", ".trashes", ".fseventsd", ".spotlight-v100"}:
        return None, None, "system directory", None

    for med_ext in MEDIA_LIBRARY_EXTS:
        if name_lower.endswith(med_ext):
            return None, None, "media library", None

    # 2. Read top-level entries (capped at 2000)
    top_entries = []
    try:
        with os.scandir(dir_path) as it:
            for entry in it:
                top_entries.append(entry)
                if len(top_entries) >= 2000:
                    break
    except (OSError, PermissionError):
        return None, None, "inaccessible directory", None

    top_names = {e.name for e in top_entries}
    top_names_lower = {e.name.lower() for e in top_entries}

    # 3. Project Unit Check
    has_project_marker = False
    for marker in PROJECT_MARKERS:
        if marker in top_names or marker.lower() in top_names_lower:
            has_project_marker = True
            break
    if not has_project_marker:
        for pattern in PROJECT_GLOBS:
            for entry_name in top_names:
                if fnmatch.fnmatch(entry_name.lower(), pattern.lower()):
                    has_project_marker = True
                    break
            if has_project_marker:
                break

    if has_project_marker:
        dest = format_destination(f"03_Development_Projects/{dir_name}", mode, scope)
        return "project", dest, "project unit", "medium"

    # 4. App Unit Check
    has_exe = any(e.name.lower().endswith(".exe") and e.is_file(follow_symlinks=False) for e in top_entries)
    has_dll = any(e.name.lower().endswith(".dll") and e.is_file(follow_symlinks=False) for e in top_entries)
    if name_lower.endswith(".app") or (has_exe and has_dll):
        dest = format_destination(f"05_Dev_Toolbox/Portable_Apps/{dir_name}", mode, scope)
        return "app", dest, "portable application unit", "medium"

    # 5. Course Folder Check
    m = COURSE_FOLDER_START_REGEX.search(dir_name)
    if m:
        code = m.group(1)
        dest = format_destination(f"02_Learning_Knowledge/Courses/{code}/{dir_name}", mode, scope)
        return "course", dest, f"course {code} folder", "medium"

    # 6. Album Check
    direct_files = [e for e in top_entries if e.is_file(follow_symlinks=False)]
    if len(direct_files) >= 5:
        img_count = sum(1 for e in direct_files if os.path.splitext(e.name)[1].lower() in EXT_IMAGES)
        vid_count = sum(1 for e in direct_files if os.path.splitext(e.name)[1].lower() in EXT_VIDEOS)
        total_f = len(direct_files)
        if (img_count / total_f) >= 0.8:
            dest = format_destination(f"04_Creative_Assets/Images/Albums/{dir_name}", mode, scope)
            return "album", dest, "image album", "medium"
        if (vid_count / total_f) >= 0.8:
            dest = format_destination(f"04_Creative_Assets/Videos/Albums/{dir_name}", mode, scope)
            return "album", dest, "video album", "medium"

    # 7. Otherwise Mixed Folder
    scope_display = f"{scope}/{dir_name}" if scope else dir_name
    return "mixed", None, f"mixed folder - call ssd_plan_organize with path={scope_display} to tidy inside it", None


def is_inside_unit_or_repo(root: str, rel_path: str) -> bool:
    """Checks if any ancestor directory between root and rel_path is a unit or .git repository."""
    clean = rel_path.replace("\\", "/").strip("/")
    parts = clean.split("/")
    if len(parts) <= 1:
        return False

    ancestors = parts[:-1]
    curr = ""
    for segment in ancestors:
        curr = f"{curr}/{segment}" if curr else segment
        if segment == ".git" or segment.lower() in DEFAULT_EXCLUDE_DIRS:
            return True

        anc_abs = os.path.join(root, curr)
        if not os.path.isdir(anc_abs):
            continue

        unit, _, _, _ = inspect_directory_unit(anc_abs, segment)
        if unit in {"project", "app"}:
            return True

    return False


